"""
observability/log_schema.py

ObservabilityEvent frozen dataclass。
本模組只做欄位定義，不包含任何 business logic。

Pydantic alignment is deferred. This module intentionally uses a
lightweight frozen dataclass.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Literal

EventType = Literal["preexec_decision", "async_explanation_update"]


@dataclass(frozen=True)
class ObservabilityEvent:
    # ── core identity ──────────────────────────────────────────────────────
    event_type: EventType
    timestamp: str                    # UTC ISO-8601, timespec="seconds"
    preexec_request_id: str | None    # uuid4().hex, generated by server
    explanation_job_id: str | None    # populated when async explanation is triggered

    # ── command context ────────────────────────────────────────────────────
    command: str | None
    tool_name: str | None
    runfile_path: str | None

    # ── deterministic decision ─────────────────────────────────────────────
    action: str | None               # "allow" | "warn" | "block"
    status: str | None               # "CONSISTENT" | "MIXED_LINEAGE" | "INSUFFICIENT_EVIDENCE" | "UNSUPPORTED_TOOL"

    # ── decision provenance ───────────────────────────────────────────
    decision_source: str | None
    # "checker_only"              — deterministic checker only
    # "checker_plus_llm_explainer"— checker + successful LLM explanation attached

    intent_source: str | None
    # "fixed_parser" — fixed-format runfile parser was used (default)
    # "unknown"      — intent fallback was enabled; cannot reliably determine
    #                  whether fallback was actually invoked (known limitation)

    # ── explanation surfacing ──────────────────────────────────────────────
    explanation_present: bool | None
    surfaced_mode: str | None
    # "explanation"      — LLM explanation was present and surfaced
    # "message_fallback" — no explanation; deterministic message shown
    # "not_surfaced"     — explanation was available but not surfaced (future)

    # ── runtime provider ──────────────────────────────────────────────────
    runtime_provider_used: bool | None
    runtime_provider_error: str | None   # null or human-readable error string

    # ── async explanation state ──────────────────────────────────
    async_explanation_status: str | None
    # "not_requested" — no async explanation job was triggered
    # "queued"        — job enqueued
    # "running"       — worker executing LLM call
    # "completed"     — explanation ready
    # "failed"        — LLM call raised exception
    # "expired"       — TTL exceeded

    # ── latency breakdown ─────────────────────────────────────────────
    # All latency fields represent SERVER CALL-SITE elapsed time only.
    # They are NOT internal module timing. Sub-call breakdown requires
    # preexec_api.py refactoring, deferred to a future round.
    ipc_request_latency_ms: float | None       # socket recv to handler entry
    checker_latency_ms: float | None           # server call-site only; None this round
    intent_fallback_latency_ms: float | None   # server call-site only; None this round
    explainer_latency_ms: float | None         # server call-site only; None this round
    surface_latency_ms: float | None           # terminal surface call; None this round
    total_preexec_latency_ms: float | None     # full handle_pre_exec() wall time
